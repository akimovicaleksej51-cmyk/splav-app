const { contextBridge, ipcRenderer } = require('electron');

const call = async (name, ...args) => {
  const r = await ipcRenderer.invoke(name, ...args);
  if (!r.ok) throw new Error(r.error);
  return r.data;
};

contextBridge.exposeInMainWorld('api', {
  state: () => call('state'),
  login: (service) => call('login', service),
  setYaToken: (token) => call('yaToken', token),
  logout: (service) => call('logout', service),
  likes: () => call('likes'),
  search: (text) => call('search', text),
  stream: (track) => call('stream', track),
  waveNext: (opts) => call('waveNext', opts),
  waveFeedback: (opts) => call('waveFeedback', opts),
  waveSettings: (s, eff) => call('waveSettings', s, eff),
  like: (track, on) => call('like', { track, on }),
  dislike: (track) => call('dislike', { track }),
  download: (track) => call('download', track),
  addFolder: () => call('addFolder'),
  removeFolder: (dir) => call('removeFolder', dir),
  openDownloads: () => call('openDownloads'),
  reveal: (file) => call('reveal', file),
  setVolume: (v) => call('setVolume', v),
  openExternal: (url) => call('openExternal', url),
  artist: (source, id) => call('artist', { source, id }),
  artistTracks: (source, id) => call('artistTracks', { source, id }),
  album: (source, id) => call('album', { source, id }),
  likeArtist: (id, on) => call('likeArtist', { id, on }),
  coverColor: (url) => call('coverColor', url),
  lyrics: (track) => call('lyrics', track),
  downloads: () => call('downloads'),
  removeDownload: (k) => call('removeDownload', k),
  playlists: () => call('playlists'),
  playlistSave: (pl) => call('playlistSave', pl),
  playlistDelete: (id) => call('playlistDelete', id),
  importPlaylist: (link) => call('importPlaylist', link),
  historyAdd: (e) => call('historyAdd', e),
  wrapped: (ym) => call('wrapped', ym),
  saveImage: (rect, name) => call('saveImage', { rect, name }),
  setPrefs: (p) => call('setPrefs', p),
  setZvToken: (t) => call('zvToken', t),
  setKeys: (k) => call('setKeys', k),
  amPlay: (pid) => call('amPlay', pid),
  amState: () => call('amState'),
  amCmd: (cmd, value) => call('amCmd', { cmd, value }),
  amCover: (artist, title) => call('amCover', { artist, title }),
  scrobble: (type, t, ts) => call('scrobble', { type, t, ts }),
  presence: (d) => call('presence', d),
  room: (b) => call('room', b),
  social: (b) => call('social', b),
  health: () => call('health'),
  updateCheck: () => call('updateCheck'),
  updateInstall: () => call('updateInstall'),
  historyStats: () => call('historyStats'),
  pendingLink: () => call('pendingLink'),
  appVersion: () => call('appVersion'),
  npUpdate: (data) => ipcRenderer.send('np:update', data),
  onCmd: (cb) => ipcRenderer.on('cmd', (_e, c) => cb(c)),
});
